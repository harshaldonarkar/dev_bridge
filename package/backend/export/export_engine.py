    def __init__(self, config=None):
        """
        Initialize the ExportEngine.
        
        Args:
            config: Configuration options for the export engine
        """
        self.config = config or {}
        self.pdf_options = {
            'page-size': 'A4',
            'margin-top': '20mm',
            'margin-right': '20mm',
            'margin-bottom': '20mm',
            'margin-left': '20mm',
            'encoding': 'UTF-8',
            'no-outline': None,
            'enable-local-file-access': None
        }
    
